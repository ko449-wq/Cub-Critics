// - Visible to the public: 'published' and 'reported'. Hidden: 'flagged' and 'removed'.
// - edited_at is NULL until the student edits the review (FR#28).
// - users/venues are RESTRICT: nothing silently erases a student's review history.
// - Deleting a review (FR#29) also deletes its reports (CASCADE); the moderation log
//   keeps its own snapshot, so the audit trail survives.
